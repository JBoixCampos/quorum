// Short names people are likely to try, for an icon in NAMES.
const ALIASES = {
  chart: 'bar-chart-3', pie: 'chart-pie', line: 'chart-line', idea: 'lightbulb', question: 'circle-help',
  ok: 'check-circle', time: 'clock', money: 'coins', team: 'users', person: 'user', bread: 'croissant',
  ai: 'sparkles', robot: 'bot', world: 'globe', house: 'home', settings: 'cog', fire: 'flame',
  water: 'droplet', growth: 'trending-up', decline: 'trending-down', love: 'heart',
};

const dir = process.argv[2];
if (!dir || !existsSync(dir)) {
  console.error('Usage: node scripts/icons.js <lucide-static/icons folder>');
  process.exit(1);
}
const icons = {};
const missing = [];
NAMES.forEach((name) => {
  const file = join(dir, `${name}.svg`);
  if (!existsSync(file)) {
    missing.push(name);
    return;
  }
  icons[name] = readFileSync(file, 'utf8')
    .replace(/^[\s\S]*?<svg[^>]*>/, '')
    .replace(/<\/svg>[\s\S]*$/, '')
    .replace(/\s*\n\s*/g, '')
    .trim();
});
if (missing.length) console.log(`Not in Lucide, left out: ${missing.join(', ')}`);

const body = Object.entries(icons).map(([k, v]) => `  '${k}': '${v.replace(/'/g, "\\'")}',`).join('\n');
const aliases = Object.entries(ALIASES).map(([k, v]) => `${k}: '${v}'`).join(', ');
writeFileSync(OUT, `// Icons for slides: a selection of Lucide (https://lucide.dev), ISC licence,
// Copyright (c) Lucide Icons and Contributors. Each entry is the inside of a
// 24 x 24 SVG drawn with strokes. Generated by scripts/icons.js: add names
// there and run it again rather than editing this file.
//
// Runs in Node and in the browser, so the parser can draw icons into the
// slides and \`quorum check\` can tell when a name does not exist.

export const ICONS = {
${body}
};

// Some short names people are likely to try.
const ALIASES = { ${aliases} };

export function iconName(name) {
  const n = String(name || '').trim().toLowerCase();
  if (ICONS[n]) return n;
  return ALIASES[n] && ICONS[ALIASES[n]] ? ALIASES[n] : null;
}

// An icon as inline SVG, or '' when the name is unknown.
export function iconSvg(name, cls = 'q-icon') {
  const n = iconName(name);
  if (!n) return '';
  return \`<svg class="\${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" data-icon="\${n}">\${ICONS[n]}</svg>\`;
}
`);
console.log(`${Object.keys(icons).length} icons written to ${OUT}`);
