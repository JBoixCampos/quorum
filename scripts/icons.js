// Writes src/shared/icons.js: the icons a talk can use, taken from Lucide
// (https://lucide.dev, ISC licence). Quorum has no dependencies, so the
// icons are copied in. To add one, put its Lucide name in NAMES and run:
//
//   npm pack lucide-static && mkdir lucide && tar xzf lucide-static-*.tgz -C lucide
//   node scripts/icons.js lucide/package/icons
//
// Keep the list short: every icon is sent with the talk.

