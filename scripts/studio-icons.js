// Writes app/js/studio-icons.js: the icons of Studio's own interface, from
// Lucide (https://lucide.dev, ISC licence). The icons a talk can use are in
// src/shared/icons.js (scripts/icons.js). To change this list:
//
//   npm pack lucide-static && mkdir lucide && tar xzf lucide-static-*.tgz -C lucide
//   node scripts/studio-icons.js lucide/package/icons

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'app', 'js', 'studio-icons.js');

const NAMES = `
undo-2 redo-2 play presentation file-down download sparkles wand-sparkles plus copy trash-2 code
search zoom-in zoom-out triangle-alert circle-check check x grip-vertical type heading pilcrow list
list-ordered image chart-column chart-bar vote users message-circle message-square timer qr-code
layers monitor columns-2 quote hash milestone gauge clipboard-copy external-link settings palette
layout-template layout-grid square-dashed command keyboard circle-stop loader-circle chevron-down
chevron-right list-checks git-branch globe wifi lightbulb pencil eye panel-left rows-3 cloud
text-cursor-input square-stack calendar move info circle-help shuffle
`.trim().split(/\s+/);

const from = process.argv[2];
if (!from) {
  console.error('Usage: node scripts/studio-icons.js <lucide icons folder>');
  process.exit(1);
}
const body = NAMES.map((name) => {
  const svg = readFileSync(join(from, `${name}.svg`), 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/\s*\n\s*/g, '').trim();
  return `  '${name}': '${inner.replace(/'/g, "\\'")}',`;
}).join('\n');
writeFileSync(OUT, `// Studio's interface icons: a selection of Lucide (https://lucide.dev), ISC
// licence, Copyright (c) Lucide Icons and Contributors. Generated by
// scripts/studio-icons.js; add names there rather than editing this file.

export const UI_ICONS = {
${body}
};

export function icon(name, cls = 'i') {
  const inner = UI_ICONS[name];
  if (!inner) return '';
  return \`<svg class="\${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${inner}</svg>\`;
}
`);
console.log(`Wrote ${NAMES.length} icons to ${OUT}`);
